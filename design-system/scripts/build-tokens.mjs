#!/usr/bin/env node
/**
 * Builds design-system/css/tokens.css from the three token tiers in design-system/tokens/.
 *
 *   primitives.json  → :root custom properties with raw values
 *   semantic.json    → :root / [data-theme] blocks; values become var(--primitive)
 *   components.json  → :root custom properties; values become var(--semantic|--primitive)
 *
 * References ("{path.to.token}") are emitted as var() so a change at any tier
 * cascades at runtime. Unknown references, duplicate names and theme modes with
 * mismatched keys fail the build.
 *
 * Usage: node design-system/scripts/build-tokens.mjs
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TOKENS_DIR = path.join(ROOT, 'tokens');
const OUT_FILE = path.join(ROOT, 'css', 'tokens.css');
const REF = /\{([^}]+)\}/g;

const readJson = async (name) => JSON.parse(await readFile(path.join(TOKENS_DIR, name), 'utf8'));

/** Flattens nested tokens into Map<"a.b.c", value>, ignoring $-prefixed metadata. */
function flatten(tree, prefix = [], out = new Map()) {
  for (const [key, node] of Object.entries(tree)) {
    if (key.startsWith('$')) continue;
    const pathParts = [...prefix, key];
    if (node && typeof node === 'object' && '$value' in node) out.set(pathParts.join('.'), String(node.$value));
    else if (node && typeof node === 'object') flatten(node, pathParts, out);
  }
  return out;
}

const toVar = (tokenPath) => `--${tokenPath.replaceAll('.', '-')}`;

function resolveRefs(value, known, source) {
  return value.replace(REF, (_, ref) => {
    if (!known.has(ref)) throw new Error(`${source}: unknown reference {${ref}}`);
    return `var(${toVar(ref)})`;
  });
}

function assertSameKeys(a, b, label) {
  const missing = [...a.keys()].filter((k) => !b.has(k)).concat([...b.keys()].filter((k) => !a.has(k)));
  if (missing.length) throw new Error(`${label}: keys differ between modes → ${missing.join(', ')}`);
}

function assertUniqueVars(...maps) {
  const seen = new Set();
  for (const map of maps) {
    for (const key of map.keys()) {
      const name = toVar(key);
      if (seen.has(name)) throw new Error(`duplicate custom property ${name}`);
      seen.add(name);
    }
  }
}

const block = (selector, entries) =>
  `${selector} {\n${entries.map(([k, v]) => `  ${toVar(k)}: ${v};`).join('\n')}\n}\n`;

async function build() {
  const primitives = flatten(await readJson('primitives.json'));
  const semanticModes = await readJson('semantic.json');
  const light = flatten(semanticModes.light);
  const dark = flatten(semanticModes.dark);
  const components = flatten(await readJson('components.json'));

  assertSameKeys(light, dark, 'semantic.json');
  assertUniqueVars(primitives, light, components);

  const known = new Set([...primitives.keys(), ...light.keys(), ...components.keys()]);
  const resolve = (map, source) => [...map].map(([k, v]) => [k, resolveRefs(v, known, `${source} → ${k}`)]);

  const css = [
    '/* GENERATED by design-system/scripts/build-tokens.mjs — edit the JSON in design-system/tokens/, not this file. */\n',
    '/* Tier 1 · primitives */',
    block(':root', resolve(primitives, 'primitives')),
    '/* Tier 2 · semantic (light is the default) */',
    block(':root,\n[data-theme="light"]', resolve(light, 'semantic.light')),
    block('[data-theme="dark"]', resolve(dark, 'semantic.dark')),
    '/* Tier 3 · components */',
    block(':root', resolve(components, 'components')),
  ].join('\n');

  await writeFile(OUT_FILE, css);
  const total = primitives.size + light.size + components.size;
  console.log(`tokens.css written: ${total} tokens (${primitives.size} primitive, ${light.size} semantic ×2 modes, ${components.size} component)`);
}

build().catch((err) => {
  console.error(`Token build failed: ${err.message}`);
  process.exit(1);
});
